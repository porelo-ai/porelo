package org.fuin.porelo.gate;

import static org.assertj.core.api.Assertions.assertThat;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Duration;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import org.fuin.porelo.core.process.Command;
import org.fuin.porelo.core.process.CommandResult;
import org.fuin.porelo.core.process.ProcessCommandRunner;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/**
 * The patch a review shows, put in the ranking's order by the gate, is the patch git prints when
 * told that order with an order file: character for character, for deletes, binary files, a
 * generated file and paths holding spaces and quotes, through real git.
 */
class ReviewOrderTest {

    private final ProcessCommandRunner real = new ProcessCommandRunner(Duration.ofSeconds(60));

    @TempDir private Path root;

    @Test
    void theReorderedPatchIsWhatGitPrintsInTheRankingsOrder() throws IOException {
        final Path mirror = root.resolve("mirror.git");
        final Path work = root.resolve("work");
        final GitGate gate = new GitGate(real, mirror, GateMode.GATEKEEPING, null);
        gate.initialize();
        git(root, "init", "--initial-branch=main", work.toString());
        write(work, "gone.txt", "to be deleted\n");
        write(work, "dir with space/gone too.txt", "also deleted\n");
        write(work, "kept.txt", "one\ntwo\n");
        write(work, "reformatted.txt", "a  b\n");
        git(work, "add", ".");
        git(work, "commit", "-q", "-m", "base");
        final String base = git(work, "rev-parse", "HEAD").standardOutput().strip();

        Files.delete(work.resolve("gone.txt"));
        Files.delete(work.resolve("dir with space/gone too.txt"));
        write(work, "kept.txt", "one\ntwo\nthree\n");
        write(work, "reformatted.txt", "a b\n");
        write(work, "a \"quoted\" name.txt", "quoted\n");
        write(work, "tab\tname.txt", "tab\n");
        write(work, "package.json", "{\"dependencies\": {}}\n");
        write(work, "made.go", "// Code generated by a tool. DO NOT EDIT.\npackage made\n");
        write(work, ".github/workflows/ci.yml", "on: push\n");
        Files.write(work.resolve("image.bin"), new byte[] {0, 1, 2, 3, (byte) 0xff, 0, 7});
        git(work, "add", "-A");
        git(work, "commit", "-q", "-m", "change");
        git(work, "push", "-q", mirror.toString(), base + ":refs/heads/main");
        git(work, "push", "-q", mirror.toString(), "HEAD:" + GitGate.INCOMING + "case");
        final GitGate.Waiting head = gate.pendingWork("case");

        for (final boolean ignoreLineEndings : List.of(false, true)) {
            final ReviewRanking.Review review = gate.rankedReview(head, base, ignoreLineEndings);

            final Path order = root.resolve("order.txt");
            final StringBuilder lines = new StringBuilder();
            for (final ReviewRanking.File file : review.files()) {
                // Escaped as git reads a pattern, so each line matches its path alone.
                lines.append(file.path().replaceAll("([\\\\*?\\[])", "\\\\$1")).append('\n');
            }
            Files.writeString(order, lines, StandardCharsets.UTF_8);
            final Path out = root.resolve("ordered.diff");
            final List<String> diff =
                    new ArrayList<>(
                            List.of(
                                    "git",
                                    "--git-dir",
                                    mirror.toString(),
                                    "diff",
                                    "--no-renames",
                                    "--patch",
                                    "-O" + order));
            if (ignoreLineEndings) {
                diff.add("--ignore-space-at-eol");
            }
            diff.addAll(List.of("--output=" + out, base, head.commit()));
            real.runOrFail(Command.of(diff));

            assertThat(review.files().getFirst().rank())
                    .as("the ranking moves files, so the order is really tested")
                    .isEqualTo(ReviewRanking.Rank.DANGEROUS);
            assertThat(review.patch())
                    .as("ignoring line endings: %s", ignoreLineEndings)
                    .isEqualTo(Files.readString(out, StandardCharsets.UTF_8));
        }
    }

    private static void write(final Path work, final String path, final String content)
            throws IOException {
        final Path file = work.resolve(path);
        Files.createDirectories(file.getParent());
        Files.writeString(file, content, StandardCharsets.UTF_8);
    }

    private CommandResult git(final Path directory, final String... arguments) {
        final List<String> all = new ArrayList<>(List.of("git"));
        all.addAll(List.of(arguments));
        return real.runOrFail(
                new Command(
                        all,
                        directory,
                        Map.of(
                                "GIT_AUTHOR_NAME",
                                "Test",
                                "GIT_AUTHOR_EMAIL",
                                "test@example.com",
                                "GIT_COMMITTER_NAME",
                                "Test",
                                "GIT_COMMITTER_EMAIL",
                                "test@example.com",
                                "GIT_CONFIG_GLOBAL",
                                "/dev/null",
                                "GIT_CONFIG_NOSYSTEM",
                                "1",
                                "GIT_TERMINAL_PROMPT",
                                "0"),
                        null));
    }
}
